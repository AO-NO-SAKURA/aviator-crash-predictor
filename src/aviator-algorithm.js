import crypto from 'crypto';

/**
 * Real Aviator Game Algorithm - Provably Fair System
 * Based on Spribe's implementation using cryptographic hashing
 */

class AviatorAlgorithm {
  constructor() {
    this.roundNumber = 0;
  }

  /**
   * Generate crash multiplier using the real Aviator algorithm
   * @param {string} serverSeed - Server-generated seed (kept secret until round ends)
   * @param {string} clientSeed - Client-provided seed for fairness verification
   * @param {number} nonce - Round number/nonce for uniqueness
   * @returns {object} - { multiplier, hash, provablyFair }
   */
  generateCrashMultiplier(serverSeed, clientSeed, nonce) {
    try {
      // Step 1: Create hash input from seeds and nonce
      const hashInput = `${serverSeed}${clientSeed}${nonce}`;
      
      // Step 2: Generate SHA256 hash
      const hash = crypto
        .createHash('sha256')
        .update(hashInput)
        .digest('hex');
      
      // Step 3: Convert hex to integer
      const hashInteger = parseInt(hash, 16);
      
      // Step 4: Check for forced crash (1 in 33 chance = ~3%)
      if (hashInteger % 33 === 0) {
        return {
          multiplier: 1.00,
          hash,
          type: 'FORCED_CRASH',
          houseedge: true,
          provablyFair: true,
          verification: {
            serverSeed,
            clientSeed,
            nonce,
            hashInput,
            hashOutput: hash
          }
        };
      }
      
      // Step 5: Calculate random number X between 0 and 1
      // Using modulo 10000 to get precision to 4 decimal places
      const randomValue = (hashInteger % 10000) / 10000;
      
      // Step 6: Apply Aviator formula: floor((1/(1-X))*100)/100
      // This ensures the multiplier is always >= 1.00
      const multiplier = Math.floor((1 / (1 - randomValue)) * 100) / 100;
      
      return {
        multiplier: Math.max(1.00, multiplier), // Ensure never below 1.00
        hash,
        type: 'NORMAL_CRASH',
        houseedge: false,
        provablyFair: true,
        randomValue: Math.round(randomValue * 10000) / 10000,
        verification: {
          serverSeed,
          clientSeed,
          nonce,
          hashInput,
          hashOutput: hash,
          formula: `floor((1/(1-${randomValue}))*100)/100`
        }
      };
    } catch (error) {
      return {
        success: false,
        error: error.message
      };
    }
  }

  /**
   * Verify a crash result (client-side verification after round ends)
   * @param {number} multiplier - The crash multiplier that occurred
   * @param {string} serverSeed - Now revealed by server
   * @param {string} clientSeed - Original client seed
   * @param {number} nonce - Round number
   * @returns {boolean} - Whether the result is valid
   */
  verifyCrashResult(multiplier, serverSeed, clientSeed, nonce) {
    const result = this.generateCrashMultiplier(serverSeed, clientSeed, nonce);
    
    if (result.error) return false;
    
    // Check if multiplier matches
    return Math.abs(result.multiplier - multiplier) < 0.01;
  }

  /**
   * Generate next server seed (for next round)
   * In real implementation, this is generated by the casino
   * @returns {string}
   */
  generateServerSeed() {
    return crypto.randomBytes(32).toString('hex');
  }

  /**
   * Generate client seed (player can provide or we generate)
   * @returns {string}
   */
  generateClientSeed() {
    return crypto.randomBytes(16).toString('hex');
  }

  /**
   * Simulate a sequence of crashes (for testing/analysis)
   * @param {number} count - Number of rounds to simulate
   * @param {string} baseSeed - Base server seed
   * @returns {array}
   */
  simulateCrashes(count = 100, baseSeed = null) {
    const crashes = [];
    const seed = baseSeed || this.generateServerSeed();

    for (let i = 0; i < count; i++) {
      const clientSeed = this.generateClientSeed();
      const result = this.generateCrashMultiplier(seed, clientSeed, i);

      crashes.push({
        roundNumber: i,
        multiplier: result.multiplier,
        type: result.type,
        timestamp: Date.now() - (count - i) * 10000,
        verified: true,
        hash: result.hash.substring(0, 8) // Show partial hash for security
      });
    }

    return crashes;
  }

  /**
   * Calculate house edge statistics from a set of crashes
   * @param {array} crashes - Array of crash results
   * @returns {object}
   */
  calculateHouseEdgeStats(crashes) {
    const forcedCrashes = crashes.filter(c => c.type === 'FORCED_CRASH').length;
    const normalCrashes = crashes.filter(c => c.type === 'NORMAL_CRASH').length;
    const houseEdgePercentage = (forcedCrashes / crashes.length) * 100;
    const avgMultiplier = crashes.reduce((sum, c) => sum + c.multiplier, 0) / crashes.length;

    return {
      totalRounds: crashes.length,
      forcedCrashes,
      normalCrashes,
      expectedHouseEdgePercentage: 3.03, // 1 in 33
      actualHouseEdgePercentage: Math.round(houseEdgePercentage * 100) / 100,
      averageMultiplier: Math.round(avgMultiplier * 100) / 100,
      minMultiplier: Math.round(Math.min(...crashes.map(c => c.multiplier)) * 100) / 100,
      maxMultiplier: Math.round(Math.max(...crashes.map(c => c.multiplier)) * 100) / 100
    };
  }
}

export const aviatorAlgorithm = new AviatorAlgorithm();
